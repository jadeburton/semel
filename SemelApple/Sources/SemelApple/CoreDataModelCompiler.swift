//
//  CoreDataModelCompiler.swift
//  SemelApple
//
//  Runs `momc` over one Core Data model, the folder Xcode's model editor writes: an
//  `.xcdatamodel` compiles to the `<name>.mom` an app loads, and a versioned
//  `.xcdatamodeld` to a `<name>.momd` folder holding every version's `.mom`, the current
//  one's optimized `.omo` and a `VersionInfo.plist` naming the current version. What comes
//  out is a file or a folder, so the result is a tree, placed at the bundle's resources as
//  Xcode places it (B-77 item 4).

import Foundation
import SemelNodeKit
import SemelDatabaseModels

// MARK: - Configuration

struct CoreDataModelCompilerConfiguration {
    let toolDescriptor: ToolDescriptor
    /// The platform's SDK on this machine, `--sdkroot`: a machine setting, written by
    /// `semel-swift prepare` as `apple.coreDataModelCompiler.sdkPath`.
    let sdkPath: String
    /// As the SDK names the platform — `macosx`, `iphonesimulator`, `iphoneos` — which
    /// decides the deployment-target flag. A literal: it says what the product is built for.
    let platform: String
    /// `13.5`: what decides the model format the app can read.
    let minimumDeploymentTarget: String
    /// The module an entity's class with no module of its own is looked up in: the target's.
    let module: String?
    /// The version of a versioned model that is current, `SPUserManager 2.xcdatamodel`: the
    /// project file's `XCVersionGroup.currentVersion`. Xcode keeps it in the model's hidden
    /// `.xccurrentversion` as well, which no push takes, so the node writes that file from
    /// this literal for momc to read.
    let currentVersion: String?

    init(properties: [String: String]) throws {
        var required = RequiredSettings(properties: properties, namespace: Self.settingNamespace)
        toolDescriptor = .init(required: &required, properties: properties)
        sdkPath = required.value("sdkPath")
        platform = required.value("platform")
        minimumDeploymentTarget = required.value("minimumDeploymentTarget")
        try required.check()

        module = properties["module"].flatMap { $0.isEmpty ? nil : $0 }
        currentVersion = properties["currentVersion"].flatMap { $0.isEmpty ? nil : $0 }
    }

    /// momc's flag for the deployment target, by platform.
    var deploymentTargetFlag: String {
        switch platform {
        case "iphoneos", "iphonesimulator": return "--iphoneos-deployment-target"
        case "appletvos", "appletvsimulator": return "--appletvos-deployment-target"
        case "watchos", "watchsimulator":   return "--watchos-deployment-target"
        case "xros", "xrsimulator":         return "--xros-deployment-target"
        default:                            return "--macosx-deployment-target"
        }
    }

    /// Pinned, like every Apple platform node's: under `apple.`.
    static let settingNamespace = "apple.coreDataModelCompiler"
}

// MARK: - Node

/// momc is a function of its input: on Xcode 26.6, Sequel Ace's model and a versioned model
/// of two versions made from it came out byte for byte the same from two runs in two folders
/// under another time zone — the `.mom`s, the `.omo` and the binary `VersionInfo.plist`,
/// whose version hashes are the entities' own. So the tree is published as momc writes it,
/// except that one naming the folder the run had is refused (`toolOutputNamesItsSandbox`),
/// which would be a different value every run.
///
/// ISSUE: an entity whose codegen is `class` or `category` has its classes generated by
/// Xcode's `--action generate` run, which this node does not make; a model that relies on it
/// compiles and its app does not. Sequel Ace's entities are `manual`.
public struct CoreDataModelCompiler: Node {
    public static let kind: UInt = 46

    // MARK: Ports

    static let configuration = "configuration"
    /// The model folder's manifest, one wire keyed by its path; read to every file through
    /// its tree and `modelFiles`, as a catalog is.
    static let model = "model"
    /// The model's subtree manifest, keyed by its path (B-135).
    static let modelTrees = "modelTrees"
    static let modelFiles = "modelFiles"
    /// The tree momc wrote: `<name>.mom`, or the `<name>.momd` folder.
    static let output = "files"
    static let infoLog = "infoLog"
    static let errorLog = "errorLog"

    static let outputFolder = "out"
    /// The file of a versioned model that names its current version, which Xcode's editor
    /// writes and momc reads.
    static let currentVersionFile = ".xccurrentversion"

    public var thisNode: NodeRecord

    public init(thisNode: NodeRecord) throws {
        self.thisNode = thisNode
    }

    public static let descriptor = NodeDescriptor(
        inputPorts: [.required(configuration), .required(model), .dynamic(modelTrees), .dynamic(modelFiles)],
        outputPorts: [output, infoLog, errorLog]
    )

    /// What each model compiles to, by extension.
    static let compiledExtensions = ["xcdatamodel": "mom", "xcdatamodeld": "momd"]

    /// `SPUserManager.xcdatamodel` -> `SPUserManager.mom`; nil for a folder that is no model.
    static func compiledName(of modelName: String) -> String? {
        let name = modelName as NSString
        guard let compiled = compiledExtensions[name.pathExtension.lowercased()] else {
            return nil
        }
        return name.deletingPathExtension + "." + compiled
    }

    // MARK: Processing

    /// The binary behind the tool version the configuration names (B-17), and the SDK tree
    /// behind `--sdkroot` (B-47).
    public func cacheKeyMaterial(input: ProcessInput) throws -> String? {
        guard case .value(let hash)? = try input.onlyWire(onOptionalPort: Self.configuration)?.value else {
            return nil
        }
        let properties = [String: String](plainText: try hash.resolveAsString())
        let lines = [sdkCacheKeyMaterial(sdkPathIn: properties),
                     toolBinaryCacheKeyMaterial(configuration: properties)].compactMap { $0 }
        return lines.isEmpty ? nil : lines.joined(separator: "\n")
    }

    /// A compile's failure belongs to the model.
    public func errorSubject(input: ProcessInput?) -> ErrorDocument.Subject? {
        input?.inputValues[Self.model]?.keys.min().map { .resource(path: $0) }
    }

    public func process(input: ProcessInput) throws -> ProcessOutput {
        let configurationText = try input.onlyWire(onRequiredPort: Self.configuration).value.expectValue().resolveAsString()
        let configuration = try CoreDataModelCompilerConfiguration(properties: [String: String](plainText: configurationText))

        let modelWire = try input.onlyWire(onRequiredPort: Self.model)
        guard let modelName = Path(modelWire.key).lastComponent, let compiledName = Self.compiledName(of: modelName) else {
            throw ErrorCondition.sourceNotTaken(path: modelWire.key, tool: "momc",
                                                takes: Self.compiledExtensions.keys.sorted().map { ".\($0)" })
        }

        // Every file of the model, through its tree, before momc runs: a model missing a
        // version would compile into a wrong `.momd`.
        let manifests = FolderTreeWalk.manifests(in: input, port: Self.model)
        let trees     = FolderTreeWalk.trees(in: input, port: Self.modelTrees)
        var treeSpecs: [String: GraphSpecNode] = [:]
        var allManifests: [String: FolderManifest] = [:]
        for manifest in manifests.map(\.manifest) {
            treeSpecs[manifest.baseFolderPath] = .folderTree(at: manifest.baseFolderPath)
            guard let tree = trees[manifest.baseFolderPath] else {
                allManifests[manifest.baseFolderPath] = manifest
                continue
            }
            allManifests.merge(try tree.folderManifests(at: manifest.baseFolderPath)) { existing, _ in existing }
        }
        let fileSpecs = FolderTreeWalk.fileSpecs(of: allManifests.keys.sorted().compactMap { allManifests[$0] })
        let specs = [Self.modelTrees: treeSpecs, Self.modelFiles: fileSpecs]
        let arrivedFiles = Set((input.inputValues[Self.modelFiles] ?? [:]).keys)
        guard !manifests.isEmpty, Set(treeSpecs.keys).isSubset(of: Set(trees.keys)),
              Set(fileSpecs.keys).isSubset(of: arrivedFiles) else {
            let pending = NodeValue.noValue(reason: .pending)
            return .init(outputValues: [Self.output: pending, Self.infoLog: pending, Self.errorLog: pending],
                         inputWireSpecs: specs)
        }

        // The model goes into the sandbox under its own name, every file at its place below
        // it, so what momc is told and what it writes name nothing of where the model is.
        let root = Path(modelWire.key)
        var inputFiles = try FolderTreeWalk.files(in: input, port: Self.modelFiles) { fullPath in
            Path(fullPath).relative(to: root).map { (Path(modelName) / $0).string } ?? fullPath
        }
        if let currentVersion = configuration.currentVersion {
            inputFiles.append(FileNameAndContent(filePath: "\(modelName)/\(Self.currentVersionFile)",
                                                 hash: try Self.currentVersionPlist(naming: currentVersion).intern()))
        }

        var arguments = ["--sdkroot=\(configuration.sdkPath)",
                         "\(configuration.deploymentTargetFlag)=\(configuration.minimumDeploymentTarget)"]
        if let module = configuration.module {
            arguments += ["--module", module]
        }
        arguments += [modelName, "\(Self.outputFolder)/"]

        let tool = try ToolRunnerRegistry.instance.tool(descriptor: configuration.toolDescriptor,
                                                        namespace:  CoreDataModelCompilerConfiguration.settingNamespace)
        let result = try tool.execute(arguments: arguments,
                                      environment: [:],
                                      inputFiles: inputFiles,
                                      expectedOutputFileNames: [],
                                      expectedOutputFolders: [Self.outputFolder])

        let subject = ErrorDocument.Subject.resource(path: modelWire.key)
        let written = result.outputTrees[Self.outputFolder] ?? []
        let tree: NodeValue
        if result.exitCode == 0, written.isEmpty {
            tree = try result.wroteNothingDocument(tool: "momc", paths: [compiledName], subject: subject).published()
        } else {
            tree = try Self.treeNamingNoSandbox(result.asTreeNodeValue(folder: Self.outputFolder, tool: "momc", subject: subject),
                                                entries: written, sandboxPath: result.resolvedSandboxPath,
                                                compiledName: compiledName, subject: subject)
        }

        return .init(outputValues: [Self.output:   tree,
                                    Self.infoLog:  .value(try result.infoOutput.intern()),
                                    Self.errorLog: .value(try result.errorOutput.intern())],
                     inputWireSpecs: specs)
    }

    /// The tree as momc wrote it, or an error when a file of it names the folder the run had.
    static func treeNamingNoSandbox(_ tree: NodeValue, entries: [TreeManifestEntry], sandboxPath: String,
                                    compiledName: String, subject: ErrorDocument.Subject) throws -> NodeValue {
        guard case .value = tree else {
            return tree
        }
        for entry in entries {
            guard case .file(let hash, _) = entry.content else {
                continue
            }
            if ToolSandbox.names(sandboxPath: sandboxPath, in: try hash.resolve()) {
                return try ErrorDocument.engine(.toolOutputNamesItsSandbox(tool: "momc", file: entry.path),
                                                subject: subject).published()
            }
        }
        return tree
    }

    /// The `.xccurrentversion` Xcode's model editor writes: an XML property list naming the
    /// current version's folder.
    static func currentVersionPlist(naming version: String) throws -> String {
        let data = try PropertyListSerialization.data(fromPropertyList: ["_XCCurrentVersionName": version],
                                                      format: .xml, options: 0)
        return String(decoding: data, as: UTF8.self)
    }
}
